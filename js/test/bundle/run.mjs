#!/usr/bin/env node
// The bundle matrix: build every model package the way our consumers actually
// build it, with the real bundlers, and fail if any target breaks.
//
// Why this exists: the JS packages are isomorphic (one import, four graphs -
// browser, SSR-in-Node, plain Node native, and each bundler's idea of the
// above), and every SSR regression we have shipped was invisible to unit tests
// because the failure only exists inside a bundler. The 0.10.2 break was a
// bundler tracing a lazy `require("koffi")` and refusing to put a native addon
// in an ESM chunk. Nothing short of running the bundler catches that class.
//
// What it does:
//   1. Stages each packages/<model>-node (plus js/, the shared core) and packs
//      them with `npm pack`, so every scenario consumes the *tarball* - the same
//      bytes npm publishes. That also catches a missing "files" or "exports"
//      entry, which is another way SSR has broken before.
//   2. Installs the tarballs once into a temp workspace alongside the bundlers.
//   3. Runs the scenario matrix below and asserts on both the exit status and
//      the emitted bundles.
//
// The wasm dist/ is generated by `mise run build-web`. When it is present (the
// wasm CI job, or a local build) the matrix uses the real one; otherwise it
// stages a stub with the same module shape so the matrix still runs anywhere,
// including in this repo's fast JS job. Real dist > stub, so CI does both.
//
// It ships in the @desert-ant-labs/core tarball as the `dal-bundle-matrix` bin,
// so a model SDK repo runs the same matrix against its own package without
// vendoring anything (see `mise run test-bundles`).
//
// Usage:
//   node test/bundle/run.mjs                 # the whole matrix, in this repo
//   npx --package @desert-ant-labs/core dal-bundle-matrix    # in an SDK repo
//   ... --list
//   ... --only esbuild-browser,next-turbopack
//   ... --skip next-webpack --keep
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

// The repo under test is the caller's, not this file's: in a model SDK repo the
// harness runs out of node_modules. Walk up from the cwd to the checkout that
// owns packages/<model>-node.
function findRepoRoot(from) {
  let dir = path.resolve(from);
  for (;;) {
    const pkgs = path.join(dir, "packages");
    if (fs.existsSync(pkgs) && fs.readdirSync(pkgs).some((d) => fs.existsSync(path.join(pkgs, d, "browser.js")))) {
      return dir;
    }
    const up = path.dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}

const REPO = findRepoRoot(process.env.DAL_REPO ?? process.cwd());

// Bundler versions are pinned by major so the matrix tracks what consumers
// install today without going fully floating.
const TOOLING = {
  next: "^16.0.0",
  react: "^19.0.0",
  "react-dom": "^19.0.0",
  vite: "^7.0.0",
  webpack: "^5.97.0",
  "webpack-cli": "^6.0.0",
  esbuild: "^0.25.0",
  "@litertjs/core": "^2.5.2",
};

// ---------------------------------------------------------------- utilities

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.findIndex((a) => a === `--${name}` || a.startsWith(`--${name}=`));
  if (i === -1) return undefined;
  const inline = args[i].includes("=") ? args[i].split("=").slice(1).join("=") : undefined;
  return inline ?? args[i + 1] ?? "";
};
const has = (name) => args.includes(`--${name}`);
const list = (v) => (v ? v.split(",").map((s) => s.trim()).filter(Boolean) : []);

const log = (...m) => console.log(...m);
const die = (m) => {
  console.error(`error: ${m}`);
  process.exit(1);
};

function run(cmd, cmdArgs, opts = {}) {
  const res = spawnSync(cmd, cmdArgs, {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    ...opts,
    env: { ...process.env, ...opts.env },
  });
  if (res.error) throw res.error;
  return { code: res.status, out: `${res.stdout ?? ""}${res.stderr ?? ""}` };
}

/** Every emitted .js/.mjs/.cjs under `dir`, concatenated. */
function emitted(dir) {
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.[cm]?js$/.test(e.name)) out.push(fs.readFileSync(p, "utf8"));
    }
  };
  if (fs.existsSync(dir)) walk(dir);
  return out.join("\n");
}

// A `node:` *specifier*, not the minifier's `{node:r}` property shorthand: only
// a quoted builtin counts.
const NODE_BUILTIN = /["'`]node:[a-z_/]+["'`]/g;

/**
 * Asserts a browser bundle carries neither the native loader nor node builtins,
 * and that it actually contains the model code (a scenario that tree-shook the
 * package away would otherwise pass while testing nothing).
 *
 * Scenarios minify, so a source comment mentioning koffi cannot trip this.
 */
function assertBrowserClean(code, label, pkgs = []) {
  const problems = [];
  if (/koffi/.test(code)) problems.push("references koffi");
  const builtins = [...new Set([...code.matchAll(NODE_BUILTIN)].map((m) => m[0]))];
  if (builtins.length) problems.push(`imports ${builtins.join(", ")}`);
  for (const p of pkgs) {
    if (p.hostGlobal && !code.includes(p.hostGlobal)) {
      problems.push(`does not contain ${p.name} (looked for ${p.hostGlobal})`);
    }
  }
  if (problems.length) throw new Error(`${label}: ${problems.join("; ")}`);
}

// ---------------------------------------------------------------- staging

/** The model node packages in this repo (a model SDK repo has exactly one). */
function findPackages() {
  const dir = path.join(REPO, "packages");
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .map((d) => path.join(dir, d))
    .filter((d) => fs.existsSync(path.join(d, "package.json")) && fs.existsSync(path.join(d, "browser.js")))
    .map((d) => {
      const pkg = JSON.parse(fs.readFileSync(path.join(d, "package.json"), "utf8"));
      const wasm = pkg.exports?.["./wasm"] ?? "";
      const codec = fs.readFileSync(path.join(d, "codec.js"), "utf8");
      return {
        dir: d,
        name: pkg.name,
        modelId: path.basename(d).replace(/-node$/, ""),
        // The global the wasm core drives, e.g. "__EmoHost": a string that must
        // survive into any bundle that really contains this package.
        hostGlobal: codec.match(/HOST_GLOBAL\s*=\s*"([^"]+)"/)?.[1],
        // "./dist/EmoWeb.wasm" -> EmoWeb.wasm
        wasmFile: path.basename(String(wasm)) || "Core.wasm",
      };
    });
}

/** The module shape `mise run build-web` emits, reduced to what the JS seams
 *  call. Used only when the real wasm dist has not been built, so the matrix
 *  runs on a machine with no Swift toolchain. */
function stubDist(dir, { modelId, wasmFile }) {
  const registry = `
// Stub wasm core (bundle matrix). The real one is emitted by \`mise run build-web\`.
const exportsFor = () => ({
  create: () => 1,
  createSelfHosted: () => 1,
  isDownloaded: () => false,
  download: async () => {},
  run: async () => new Uint8Array([0, 0, 0, 0]),
  endCallGroup: () => {},
  destroy: () => {},
  flushTelemetry: () => {},
});
export function register() {
  globalThis.__DesertAntExports ??= {};
  globalThis.__DesertAntExports[${JSON.stringify(modelId)}] = exportsFor();
}
`;
  fs.mkdirSync(path.join(dir, "platforms"), { recursive: true });
  fs.writeFileSync(path.join(dir, "registry.js"), registry);
  // Browser entry: platform-browser.js calls init().
  fs.writeFileSync(
    path.join(dir, "index.js"),
    'import { register } from "./registry.js";\nexport async function init() { register(); }\n',
  );
  // Node entry: platform-node.js calls instantiate(await defaultNodeSetup({})).
  fs.writeFileSync(
    path.join(dir, "instantiate.js"),
    'import { register } from "./registry.js";\nexport async function instantiate() { register(); }\n',
  );
  fs.writeFileSync(
    path.join(dir, "platforms", "node.js"),
    "export async function defaultNodeSetup() { return {}; }\n",
  );
  fs.writeFileSync(
    path.join(dir, "platforms", "browser.js"),
    "export async function defaultBrowserSetup() { return {}; }\n",
  );
  fs.writeFileSync(path.join(dir, wasmFile), "");
}

/** Copy a package into the workspace, filling in a stub dist when the real wasm
 *  build has not run, then `npm pack` it. Returns the tarball path. */
function stage(srcDir, work, stub) {
  const staged = path.join(work, "staged", path.basename(srcDir));
  fs.mkdirSync(path.dirname(staged), { recursive: true });
  fs.cpSync(srcDir, staged, {
    recursive: true,
    filter: (p) => !p.includes("node_modules") && !p.endsWith(".tgz"),
  });
  let real = true;
  if (stub) {
    const dist = path.join(staged, "dist");
    real = fs.existsSync(path.join(dist, "instantiate.js"));
    if (!real) {
      fs.rmSync(dist, { recursive: true, force: true });
      fs.mkdirSync(dist, { recursive: true });
      stubDist(dist, stub);
    }
  }
  // The published tarball must carry the license; packing without it fails the
  // publish task, so keep the matrix honest about it too.
  const license = path.join(staged, "LICENSE.md");
  const repoLicense = path.join(REPO, "LICENSE.md");
  if (!fs.existsSync(license) && fs.existsSync(repoLicense)) fs.copyFileSync(repoLicense, license);

  const dest = path.join(work, "tarballs");
  fs.mkdirSync(dest, { recursive: true });
  const res = run("npm", ["pack", "--silent", "--pack-destination", dest], { cwd: staged });
  if (res.code !== 0) die(`npm pack failed for ${srcDir}:\n${res.out}`);
  const tgz = res.out.trim().split("\n").pop().trim();
  return { tarball: path.join(dest, path.basename(tgz)), realDist: real };
}

// ---------------------------------------------------------------- scenarios
//
// Each scenario is one way a consumer builds or runs a model package. `pkgs` is
// every model package in the repo; scenarios that bundle import all of them at
// once so one build covers the matrix.

const scenarios = [
  {
    name: "node-ssr-import",
    what: "plain Node imports the universal entry (framework SSR pass)",
    run({ work, pkgs }) {
      for (const p of pkgs) {
        const src = `await import(${JSON.stringify(p.name)}); console.log("OK");`;
        const res = run(process.execPath, ["--input-type=module", "-e", src], { cwd: work });
        if (res.code !== 0 || !res.out.includes("OK")) {
          throw new Error(`${p.name} failed to import in Node:\n${res.out}`);
        }
      }
    },
  },
  {
    name: "node-native-import",
    what: "plain Node imports the /native entry (koffi path)",
    run({ work, pkgs }) {
      for (const p of pkgs) {
        const src = `await import(${JSON.stringify(`${p.name}/native`)}); console.log("OK");`;
        const res = run(process.execPath, ["--input-type=module", "-e", src], { cwd: work });
        if (res.code !== 0 || !res.out.includes("OK")) {
          throw new Error(`${p.name}/native failed to import in Node:\n${res.out}`);
        }
      }
    },
  },
  {
    name: "esbuild-browser",
    what: "esbuild bundles the universal entry for the browser",
    run({ work, pkgs, bin }) {
      const app = mkApp(work, "esbuild-browser", pkgs);
      const out = path.join(app, "out");
      const res = run(bin("esbuild"), [
        path.join(app, "entry.js"), "--bundle", "--minify", "--format=esm",
        "--platform=browser", "--outdir=" + out,
      ], { cwd: work });
      if (res.code !== 0) throw new Error(`esbuild (browser) failed:\n${res.out}`);
      assertBrowserClean(emitted(out), "esbuild browser bundle", pkgs);
    },
  },
  {
    name: "esbuild-node",
    what: "esbuild bundles the universal entry for a Node/SSR target",
    run({ work, pkgs, bin }) {
      const app = mkApp(work, "esbuild-node", pkgs);
      const out = path.join(app, "out");
      // No externals on purpose: this is the strict version of what an SSR
      // bundler does, so a native addon sneaking into the graph fails loudly
      // ("No loader is configured for .node files") instead of at a user's
      // `next build`.
      const res = run(bin("esbuild"), [
        path.join(app, "entry.js"), "--bundle", "--format=esm",
        "--platform=node", "--outdir=" + out,
      ], { cwd: work });
      if (res.code !== 0) throw new Error(`esbuild (node) failed:\n${res.out}`);
      if (/koffi/.test(emitted(out))) {
        throw new Error("the SSR bundle pulled in koffi (it belongs to the /native entry only)");
      }
    },
  },
  {
    name: "vite-browser",
    what: "vite/rollup builds a browser app",
    run({ work, pkgs, bin }) {
      const app = mkApp(work, "vite-browser", pkgs);
      fs.writeFileSync(path.join(app, "index.html"),
        '<!doctype html><html><body><script type="module" src="/entry.js"></script></body></html>\n');
      fs.writeFileSync(path.join(app, "vite.config.js"),
        'export default { build: { outDir: "out", emptyOutDir: true, rollupOptions: { onwarn(w, d) { if (w.code === "MODULE_LEVEL_DIRECTIVE") return; d(w); } } } };\n');
      const res = run(bin("vite"), ["build", "--logLevel", "warn"], { cwd: app });
      if (res.code !== 0) throw new Error(`vite build failed:\n${res.out}`);
      assertBrowserClean(emitted(path.join(app, "out")), "vite browser bundle", pkgs);
    },
  },
  {
    name: "webpack-web",
    what: "webpack builds a browser app (target: web)",
    run({ work, pkgs, bin }) {
      const app = mkApp(work, "webpack-web", pkgs);
      fs.writeFileSync(path.join(app, "webpack.config.mjs"), `
import path from "node:path";
export default {
  mode: "production",
  target: "web",
  entry: path.resolve("${app.replace(/\\/g, "\\\\")}", "entry.js"),
  output: { path: path.resolve("${app.replace(/\\/g, "\\\\")}", "out"), module: true, chunkFormat: "module" },
  experiments: { outputModule: true, topLevelAwait: true },
  stats: "errors-warnings",
};
`);
      const res = run(bin("webpack"), ["--config", path.join(app, "webpack.config.mjs")], { cwd: work });
      if (res.code !== 0) throw new Error(`webpack (web) failed:\n${res.out}`);
      assertBrowserClean(emitted(path.join(app, "out")), "webpack browser bundle", pkgs);
    },
  },
  {
    name: "next-turbopack",
    what: "next build (Turbopack): a client component, rendered by the SSR pass",
    run(ctx) {
      nextBuild(ctx, "next-turbopack", { args: [], native: false });
    },
  },
  {
    name: "next-webpack",
    what: "next build (webpack): a client component, rendered by the SSR pass",
    run(ctx) {
      nextBuild(ctx, "next-webpack", { args: ["--webpack"], native: false });
    },
  },
  {
    name: "next-native-route",
    what: "next build (Turbopack): a server route on the /native entry",
    run(ctx) {
      nextBuild(ctx, "next-native-route", { args: [], native: true, client: false });
    },
  },
];

/** A tiny app whose entry imports every model package's universal entry. */
function mkApp(work, name, pkgs) {
  const app = path.join(work, "apps", name);
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(app, { recursive: true });
  const imports = pkgs
    .map((p, i) => `import * as m${i} from ${JSON.stringify(p.name)};`)
    .join("\n");
  const uses = pkgs.map((_, i) => `m${i}`).join(", ");
  fs.writeFileSync(path.join(app, "entry.js"), `${imports}\nglobalThis.__used = [${uses}];\n`);
  fs.writeFileSync(path.join(app, "package.json"), JSON.stringify({ name, type: "module", private: true }, null, 2));
  return app;
}

/**
 * A Next App Router build, in the two shapes a consumer uses.
 *
 * `client: true` is the regression that started this: a page whose *client*
 * component imports the model, so Next renders it in Node for the
 * Client-Component SSR pass and follows the `#platform` seam's "default"
 * condition. Deliberately built with a stock config - no `serverExternalPackages`
 * - because that is the app that broke, and an escape hatch in the config would
 * hide exactly the regression this scenario exists to catch.
 *
 * `native: true` is the server-side shape: a route handler on the `/native`
 * entry. koffi is a real native addon that loads at runtime and is never
 * bundled, so this one does declare it external. That is the documented
 * configuration for server-side use, and building it here keeps the docs honest.
 */
function nextBuild({ work, pkgs, bin }, name, { args: extraArgs, native, client = true }) {
  const app = path.join(work, "apps", name);
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(path.join(app, "app"), { recursive: true });

  const importAll = (subpath) =>
    pkgs.map((p, i) => `import * as m${i} from ${JSON.stringify(p.name + subpath)};`).join("\n");
  const uses = pkgs.map((_, i) => `m${i}`).join(", ");

  if (client) {
    fs.writeFileSync(path.join(app, "app", "model.jsx"), `"use client";
${importAll("")}

export default function Model() {
  return <p>{"models: " + [${uses}].filter(Boolean).length}</p>;
}
`);
    fs.writeFileSync(path.join(app, "app", "page.jsx"), `import Model from "./model";

export default function Page() {
  return <main><Model /></main>;
}
`);
  } else {
    fs.writeFileSync(path.join(app, "app", "page.jsx"),
      "export default function Page() { return <main>ok</main>; }\n");
  }

  if (native) {
    fs.mkdirSync(path.join(app, "app", "api", "native"), { recursive: true });
    fs.writeFileSync(path.join(app, "app", "api", "native", "route.js"), `${importAll("/native")}

export const dynamic = "force-dynamic";

export async function GET() {
  return Response.json({ loaded: [${uses}].filter(Boolean).length });
}
`);
  }

  fs.writeFileSync(path.join(app, "app", "layout.jsx"), `export const metadata = { title: "bundle matrix" };

export default function RootLayout({ children }) {
  return <html lang="en"><body>{children}</body></html>;
}
`);
  // The native app declares koffi external (it is a runtime-loaded addon); the
  // client/SSR app runs a stock config on purpose.
  const config = native ? '  serverExternalPackages: ["koffi"],\n' : "";
  fs.writeFileSync(path.join(app, "next.config.mjs"), `export default {
${config}};
`);
  fs.writeFileSync(path.join(app, "package.json"), JSON.stringify({ name, private: true }, null, 2));

  const res = run(bin("next"), ["build", ...extraArgs], {
    cwd: app,
    env: { NEXT_TELEMETRY_DISABLED: "1", CI: "1" },
  });
  if (res.code !== 0) throw new Error(`next build failed:\n${res.out}`);

  // Build success covers the SSR/server graphs. The client chunks are what ships
  // to a browser, so assert that half stays clean too.
  if (client) {
    assertBrowserClean(emitted(path.join(app, ".next", "static")), `${name} client chunks`, pkgs);
  }
}

// ---------------------------------------------------------------- driver

function main() {
  if (has("list")) {
    for (const s of scenarios) log(`${s.name.padEnd(18)} ${s.what}`);
    return;
  }
  const only = list(flag("only"));
  const skip = list(flag("skip"));
  const chosen = scenarios.filter(
    (s) => (only.length === 0 || only.includes(s.name)) && !skip.includes(s.name),
  );
  if (!chosen.length) die(`no scenarios matched (try --list)`);

  if (!REPO) die("no packages/<model>-node found above the working directory");
  const pkgDirs = findPackages();
  if (!pkgDirs.length) die("no model packages found under packages/");

  const work = fs.mkdtempSync(path.join(os.tmpdir(), "dal-bundle-"));
  log(`repo: ${REPO}`);
  log(`workspace: ${work}`);

  // 1. Pack every model package, exactly as npm publishes them. In this repo the
  //    shared core is packed from js/ too, so a change to both halves is tested
  //    together; in a model SDK repo there is no js/, and the package's declared
  //    @desert-ant-labs/core version installs from npm - which is what that
  //    repo's consumers would get.
  const coreDir = path.join(REPO, "js");
  const isCoreRepo =
    fs.existsSync(path.join(coreDir, "package.json")) &&
    JSON.parse(fs.readFileSync(path.join(coreDir, "package.json"), "utf8")).name === "@desert-ant-labs/core";
  const core = isCoreRepo ? stage(coreDir, work, null) : null;
  const pkgs = pkgDirs.map((p) => ({ ...p, ...stage(p.dir, work, p) }));
  for (const p of pkgs) {
    log(`packed ${p.name} (${p.realDist ? "real wasm dist" : "stub dist - run `mise run build-web` for the real one"})`);
  }

  // 2. One install for the whole matrix: the tarballs plus the bundlers. The
  //    scenario apps live in subdirectories and resolve up into this
  //    node_modules, so nothing is installed twice.
  const deps = { ...TOOLING };
  if (core) deps["@desert-ant-labs/core"] = `file:${core.tarball}`;
  else log("no js/ in this repo: @desert-ant-labs/core installs from npm");
  for (const p of pkgs) deps[p.name] = `file:${p.tarball}`;
  fs.writeFileSync(
    path.join(work, "package.json"),
    JSON.stringify({ name: "dal-bundle-matrix", private: true, type: "module", dependencies: deps }, null, 2),
  );
  log("installing bundlers + packed tarballs...");
  const install = run("npm", ["install", "--no-audit", "--no-fund", "--loglevel", "error"], { cwd: work });
  if (install.code !== 0) die(`npm install failed:\n${install.out}`);

  const bin = (name) => path.join(work, "node_modules", ".bin", name);
  const ctx = { work, pkgs, bin };

  // 3. Run the matrix, reporting every failure rather than stopping at the first.
  const failures = [];
  for (const s of chosen) {
    const started = Date.now();
    try {
      s.run(ctx);
      log(`ok   ${s.name}  (${((Date.now() - started) / 1000).toFixed(1)}s)  ${s.what}`);
    } catch (e) {
      failures.push([s.name, e]);
      log(`FAIL ${s.name}  (${((Date.now() - started) / 1000).toFixed(1)}s)  ${s.what}`);
    }
  }

  if (has("keep")) log(`kept workspace: ${work}`);
  else fs.rmSync(work, { recursive: true, force: true });

  if (failures.length) {
    console.error(`\n${failures.length} of ${chosen.length} scenarios failed:\n`);
    for (const [name, e] of failures) console.error(`--- ${name}\n${e.message}\n`);
    process.exit(1);
  }
  log(`\nall ${chosen.length} scenarios passed`);
}

main();
