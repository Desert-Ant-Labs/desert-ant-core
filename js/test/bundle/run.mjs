/** A tiny app whose entry imports every model package's universal entry. */
function mkApp(work, name, pkgs) {
  const app = path.join(work, "apps", name);
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(app, { recursive: true });
  const imports = pkgs
    .map((p, i) => `import * as m${i} from ${JSON.stringify(p.name)};`)
    .join("\n");
  const uses = pkgs.map((_, i) => `m${i}`).join(", ");
  fs.writeFileSync(path.join(app, "entry.js"), `${imports}\nglobalThis.__used = [${uses}];\n`);
  fs.writeFileSync(path.join(app, "package.json"), JSON.stringify({ name, type: "module", private: true }, null, 2));
  return app;
}

/**
 * A Next App Router build, in the two shapes a consumer uses.
 *
 * `client: true` is the regression that started this: a page whose *client*
 * component imports the model, so Next renders it in Node for the
 * Client-Component SSR pass and follows the `#platform` seam's "default"
 * condition. Deliberately built with a stock config - no `serverExternalPackages`
 * - because that is the app that broke, and an escape hatch in the config would
 * hide exactly the regression this scenario exists to catch.
 *
 * `native: true` is the server-side shape: a route handler on the `/native`
 * entry. koffi is a real native addon that loads at runtime and is never
 * bundled, so this one does declare it external. That is the documented
 * configuration for server-side use, and building it here keeps the docs honest.
 */
function nextBuild({ work, pkgs, bin }, name, { args: extraArgs, native, client = true }) {
  const app = path.join(work, "apps", name);
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(path.join(app, "app"), { recursive: true });

  // The "/native" app covers only the packages that have that entry; the
  // universal one covers all of them.
  const forSubpath = (subpath) => (subpath === "/native" ? pkgs.filter((p) => p.native) : pkgs);
  const importAll = (subpath) =>
    forSubpath(subpath)
      .map((p, i) => `import * as m${i} from ${JSON.stringify(p.name + subpath)};`)
      .join("\n");
  const usesFor = (subpath) => forSubpath(subpath).map((_, i) => `m${i}`).join(", ");
  const uses = usesFor("");

  if (client) {
    fs.writeFileSync(path.join(app, "app", "model.jsx"), `"use client";
${importAll("")}

export default function Model() {
  return <p>{"models: " + [${uses}].filter(Boolean).length}</p>;
}
`);
    fs.writeFileSync(path.join(app, "app", "page.jsx"), `import Model from "./model";

export default function Page() {
  return <main><Model /></main>;
}
`);
  } else {
    fs.writeFileSync(path.join(app, "app", "page.jsx"),
      "export default function Page() { return <main>ok</main>; }\n");
  }

  if (native) {
    fs.mkdirSync(path.join(app, "app", "api", "native"), { recursive: true });
    fs.writeFileSync(path.join(app, "app", "api", "native", "route.js"), `${importAll("/native")}

export const dynamic = "force-dynamic";

export async function GET() {
  return Response.json({ loaded: [${usesFor("/native")}].filter(Boolean).length });
}
`);
  }

  fs.writeFileSync(path.join(app, "app", "layout.jsx"), `export const metadata = { title: "bundle matrix" };

export default function RootLayout({ children }) {
  return <html lang="en"><body>{children}</body></html>;
}
`);
  // The native app declares koffi external (it is a runtime-loaded addon); the
  // client/SSR app runs a stock config on purpose.
  const config = native ? '  serverExternalPackages: ["koffi"],\n' : "";
  fs.writeFileSync(path.join(app, "next.config.mjs"), `export default {
${config}};
`);
  fs.writeFileSync(path.join(app, "package.json"), JSON.stringify({ name, private: true }, null, 2));

  const res = run(bin("next"), ["build", ...extraArgs], {
    cwd: app,
    env: { NEXT_TELEMETRY_DISABLED: "1", CI: "1" },
  });
  if (res.code !== 0) throw new Error(`next build failed:\n${res.out}`);

  // The client chunks are what ships to a browser, so assert that half stays
  // clean.
  if (client) {
    assertBrowserClean(emitted(path.join(app, ".next", "static")), `${name} client chunks`, pkgs,
    emittedFiles(path.join(app, ".next", "static")));
  }

  // And the SSR graph carries no native addon. A build failure covers this
  // today, but only by accident of Turbopack's error message: a consumer hit
  // "non-ecmascript placeable asset ... not placeable in ESM chunks" because a
  // client component's SSR pass resolved the node export condition and reached
  // koffi. Asserting it directly names the thing that went wrong. The /native
  // app is exempt: that entry is server-only and declares koffi external, which
  // is the supported way to reach it.
  if (!native) {
    const server = path.join(app, ".next", "server");
    const addons = [];
    const walk = (d) => {
      if (!fs.existsSync(d)) return;
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, e.name);
        if (e.isDirectory()) walk(p);
        else if (e.name.endsWith(".node")) addons.push(path.relative(server, p));
      }
    };
    walk(server);
    const requiresKoffi = emittedFiles(server)
      .filter((f) => /require\(\s*["'`]koffi["'`]\)|from\s*["'`]koffi["'`]/.test(f.code))
      .map((f) => f.name);
    const problems = [];
    if (addons.length) problems.push(`native addons in the SSR graph: ${addons.join(", ")}`);
    if (requiresKoffi.length) problems.push(`SSR chunks require koffi: ${requiresKoffi.join(", ")}`);
    if (problems.length) throw new Error(`${name} server graph: ${problems.join("; ")}`);
  }
}

// ---------------------------------------------------------------- driver

function main() {
  // Writes a stub dist into each package that has no real one, in place. This
  // is what lets test:node run on a machine (or CI job) with no Swift wasm
  // toolchain: its SSR-import assertion needs dist/ to exist with the right
  // module shape, and the real-dist import is proven by the bundle matrix and
  // the browser suite where build:wasm has run.
  if (has("stage-stub-dist")) {
    if (!REPO) die("no packages/<model>-node found above the working directory");
    for (const p of findPackages()) {
      const dist = path.join(p.dir, "dist");
      if (fs.existsSync(path.join(dist, "instantiate.js"))) {
        log(`${p.name}: real dist present, leaving it alone`);
        continue;
      }
      fs.rmSync(dist, { recursive: true, force: true });
      fs.mkdirSync(dist, { recursive: true });
      stubDist(dist, p);
      log(`${p.name}: staged stub dist`);
    }
    return;
  }
  if (has("list")) {
    for (const s of scenarios) log(`${s.name.padEnd(18)} ${s.what}`);
    return;
  }
  const only = list(flag("only"));
  const skip = list(flag("skip"));
  const chosen = scenarios.filter(
    (s) => (only.length === 0 || only.includes(s.name)) && !skip.includes(s.name),
  );
  if (!chosen.length) die(`no scenarios matched (try --list)`);

  if (!REPO) die("no packages/<model>-node found above the working directory");
  const pkgDirs = findPackages();
  if (!pkgDirs.length) die("no model packages found under packages/");

  const work = fs.mkdtempSync(path.join(os.tmpdir(), "dal-bundle-"));
  log(`repo: ${REPO}`);
  log(`workspace: ${work}`);

  // 1. Pack every model package and the shared core exactly as npm publishes
  //    them, so a change to either half is tested against the other.
  const core = stage(path.join(REPO, "js"), work, null);
  const pkgs = pkgDirs.map((p) => ({ ...p, ...stage(p.dir, work, p) }));
  for (const p of pkgs) {
    log(`packed ${p.name} (${p.realDist ? "real wasm dist" : "stub dist - run `mise run build:wasm` for the real one"})`);
  }

  // 2. One install for the whole matrix: the tarballs plus the bundlers. The
  //    scenario apps live in subdirectories and resolve up into this
  //    node_modules, so nothing is installed twice.
  const deps = { ...TOOLING };
  deps["@desert-ant-labs/core"] = `file:${core.tarball}`;
  for (const p of pkgs) deps[p.name] = `file:${p.tarball}`;
  fs.writeFileSync(
    path.join(work, "package.json"),
    JSON.stringify({ name: "dal-bundle-matrix", private: true, type: "module", dependencies: deps }, null, 2),
  );
  log("installing bundlers + packed tarballs...");
  const install = run("npm", ["install", "--no-audit", "--no-fund", "--loglevel", "error"], { cwd: work });
  if (install.code !== 0) die(`npm install failed:\n${install.out}`);

  const bin = (name) => path.join(work, "node_modules", ".bin", name);
  const ctx = { work, pkgs, bin };

  // 3. Run the matrix, reporting every failure rather than stopping at the first.
  const failures = [];
  for (const s of chosen) {
    const started = Date.now();
    try {
      s.run(ctx);
      log(`ok   ${s.name}  (${((Date.now() - started) / 1000).toFixed(1)}s)  ${s.what}`);
    } catch (e) {
      failures.push([s.name, e]);
      log(`FAIL ${s.name}  (${((Date.now() - started) / 1000).toFixed(1)}s)  ${s.what}`);
    }
  }

  if (has("keep")) log(`kept workspace: ${work}`);
  else fs.rmSync(work, { recursive: true, force: true });

  if (failures.length) {
    console.error(`\n${failures.length} of ${chosen.length} scenarios failed:\n`);
    for (const [name, e] of failures) console.error(`--- ${name}\n${e.message}\n`);
    process.exit(1);
  }
  log(`\nall ${chosen.length} scenarios passed`);
}

main();
