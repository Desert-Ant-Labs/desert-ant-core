#!/usr/bin/env node
// Generate Eye's tag constants from the model's eye_meta.json (its `tags` section, built in ml-eye), for every SDK:
//
//   Sources/Eye/Tags.swift                                    Tag.dog, Tag.groupShot, ...
//   packages/eye-kotlin/src/main/kotlin/ai/desertant/eye/Tags.kt
//   packages/eye-node/tags.js, packages/eye-node/tags.d.ts
//
// Run it whenever the pinned weights change:  node Tools/eye-tags.mjs <eye_meta.json>
// EyeTests fails when the constants and the model's tags disagree.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const meta = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const spec = meta.tags;
if (!spec) throw new Error(`${process.argv[2]} has no tags section`);

const CATEGORY = {
  type: "Photo type",
  keep: "Keep or delete",
  sensitive: "Sensitive content",
  scene: "Scene (Open Images)",
  people: "People",
  quality: "Quality",
  photo: "Photo",
  face: "Face",
};
const tags = new Map();
const add = (id, category, name) => {
  const t = tags.get(id) ?? { id, categories: [], name };
  if (!t.categories.includes(category)) t.categories.push(category);
  tags.set(id, t);
};
for (const t of spec.model) add(t.id, t.category, t.name);
for (const t of spec.photo) add(t.id, t.category ?? "photo");
for (const t of spec.face) add(t.id, "face");
const all = [...tags.values()].sort((a, b) => a.id.localeCompare(b.id));

const camel = (id) => id.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const SWIFT_KEYWORDS = new Set(["as", "case", "class", "default", "do", "else", "for", "func", "if", "import", "in", "init",
  "is", "let", "operator", "protocol", "repeat", "return", "self", "static", "struct", "super", "switch", "throw", "try",
  "var", "where", "while", "Type", "Protocol"]);
const KOTLIN_KEYWORDS = new Set(["as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in",
  "interface", "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "val",
  "var", "when", "while"]);
const doc = (t) => `${t.categories.map((c) => CATEGORY[c] ?? c).join(", ")}${t.name ? `: ${t.name}` : ""}`;
const header = (c) => `${c} Generated by Tools/eye-tags.mjs from eye_meta.json (${all.length} tags). Do not edit.\n`;
const write = (rel, text) => {
  fs.writeFileSync(path.join(ROOT, rel), text);
  console.log(`wrote ${rel}`);
};

for (const t of all) {
  if (!/^[a-z][a-z0-9_]*$/.test(t.id)) throw new Error(`tag id ${t.id} is not snake_case`);
}

write("Sources/Eye/Tags.swift", header("//") + `
public extension Tag {
${all.map((t) => {
  const n = camel(t.id);
  return `    /// ${doc(t)}.\n    static let ${SWIFT_KEYWORDS.has(n) ? `\`${n}\`` : n} = Tag("${t.id}")`;
}).join("\n")}
}

extension Tag {
    /// Every tag the pinned model has, for the test that keeps this file current.
    static let known: Set<String> = [
${all.map((t) => `        "${t.id}",`).join("\n")}
    ]
}
`);

write("packages/eye-kotlin/src/main/kotlin/ai/desertant/eye/Tags.kt", header("//") + `
package ai.desertant.eye

/** Eye's tags, as constants: \`Tags.DOG\`. A newer model may add tags, which \`Tag("name")\` reaches. */
object Tags {
${all.map((t) => `    /** ${doc(t)}. */\n    @JvmField val ${t.id.toUpperCase()} = Tag("${t.id}")`).join("\n")}

    /** Every tag the pinned model has. */
    @JvmField val ALL: List<Tag> = listOf(${all.map((t) => t.id.toUpperCase()).join(", ")})
}
`);

write("packages/eye-node/tags.js", header("//") + `
/** Eye's tags by name: \`Tag.groupShot === "group_shot"\`. */
export const Tag = Object.freeze({
${all.map((t) => `  ${camel(t.id)}: "${t.id}",`).join("\n")}
});
`);

write("packages/eye-node/tags.d.ts", header("//") + `
/** Every tag the pinned model has. A newer model may add more; any string is accepted where a tag is. */
export type TagId =
${all.map((t) => `  | "${t.id}"`).join("\n")};

/** Eye's tags by name: \`Tag.groupShot === "group_shot"\`. */
export declare const Tag: {
${all.map((t) => `  /** ${doc(t)}. */\n  readonly ${camel(t.id)}: "${t.id}";`).join("\n")}
};
`);
